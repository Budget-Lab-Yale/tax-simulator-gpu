"""Generator for the compiled-law schema document.

`docs/compiled_law_schema.md` is the field inventory the calculator is written
against, generated from the frozen schema. `tests/unit/law/test_schema_doc.py`
regenerates it and fails if the file on disk differs.

Regenerate after any change to the field schema:

    uv run --no-sync python -m taxmodel.law.schema_doc
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from .compile import FILING_STATUS_LABELS

# Paths of the generated document and the frozen schema it describes.
DOC_PATH = Path("docs/compiled_law_schema.md")
FROZEN_SCHEMA = Path("tests/golden/fixtures/law/compiled_baseline_schema.json")


def render(schema: dict[str, Any]) -> str:
    """The whole document, from a schema dictionary."""
    fields = schema["fields"]
    years = schema["years"]
    shape = schema["array_shape"]

    by_unit: dict[str, int] = {}
    for field in fields:
        by_unit[field["units"]] = by_unit.get(field["units"], 0) + 1

    lines: list[str] = []
    lines.append("# The compiled tax law schema")
    lines.append("")
    lines.append(
        "Generated by `src/taxmodel/law/schema_doc.py` from the frozen baseline "
        "compile in `tests/golden/fixtures/law/`. Do not edit by hand."
    )
    lines.append("")
    lines.append("## Shape")
    lines.append("")
    lines.append(
        f"Every field is a `float64` array indexed `[year, filing_status, slot]`, "
        f"shaped `{tuple(shape)}` for this compile."
    )
    lines.append("")
    lines.append(f"- Years: {years[0]}–{years[-1]} ({len(years)} of them). The parser")
    lines.append(
        "  reads from 2014 regardless, because carry-forward and indexation both "
        "look at"
    )
    lines.append("  years the run does not simulate.")
    lines.append("- Filing status, in order: " + ", ".join(
        f"{code} {FILING_STATUS_LABELS[code]}" for code in schema["filing_statuses"]
    ) + ".")
    lines.append(
        f"- Slots: {schema['max_brackets']} (`MAX_BRACKETS`). A schedule shorter "
        "than that leaves the"
    )
    lines.append(
        "  remaining slots inactive; a law needing more is a lint error, not a "
        "reshape."
    )
    lines.append(
        "- Padding is `NaN`, and every field ships an `active` mask of the same "
        "shape."
    )
    lines.append(
        "  Inactive means the law has nothing there: a slot past the end of the "
        "schedule,"
    )
    lines.append("  or a year before the first one the author stated a value for.")
    lines.append("")
    lines.append("## Reading the columns")
    lines.append("")
    lines.append("| column | meaning |")
    lines.append("| --- | --- |")
    lines.append(
        "| units | what the numbers are denominated in: dollars, a rate, a share "
        "of AGI, a count of people or years, a calendar year, a regime code, or "
        "an on/off indicator. |"
    )
    lines.append(
        "| slots | how many slots the law fills in this compile. One means the "
        "field is a scalar and its `tax_law.csv` column carries no index. |"
    )
    lines.append(
        "| by FS | whether the filing-status mapper gives the four statuses "
        "different values. A field that does not vary is still stored four times. |"
    )
    lines.append(
        "| indexed | whether the law grows this field with a price or wage index. |"
    )
    lines.append(
        "| mapper | whether the field is built by a filing-status mapper from other "
        "subparameters of its file, rather than stated directly. |"
    )
    lines.append(
        "| grad | whether the field belongs in the differentiable parameter "
        "vector. Switches, counts, calendar years and regime codes do not; "
        "neither do individual infinite entries, which say a limit does not "
        "bind. |"
    )
    lines.append("")
    lines.append("## Totals")
    lines.append("")
    lines.append(f"- Fields: {len(fields)}")
    lines.append(
        f"- Differentiable fields: {sum(1 for f in fields if f['differentiable'])}"
    )
    lines.append(f"- Indexed fields: {sum(1 for f in fields if f['indexed'])}")
    lines.append(
        f"- Built by a filing-status mapper: "
        f"{sum(1 for f in fields if f['from_mapper'])}"
    )
    lines.append("- By units: " + ", ".join(
        f"{unit} {count}" for unit, count in sorted(by_unit.items())
    ))
    lines.append("")

    current = None
    for field in fields:
        if field["parameter"] != current:
            current = field["parameter"]
            lines.append("")
            lines.append(f"## `{current}`")
            lines.append("")
            lines.append("| field | units | slots | by FS | indexed | mapper | grad |")
            lines.append("| --- | --- | --- | --- | --- | --- | --- |")
        lines.append(
            "| `{name}` | {units} | {slots} | {fs} | {indexed} | {mapper} | {grad} |".format(
                name=field["name"],
                units=field["units"],
                slots=field["slots_used"],
                fs=_tick(field["varies_by_filing_status"]),
                indexed=_tick(field["indexed"]),
                mapper=_tick(field["from_mapper"]),
                grad=_tick(field["differentiable"]),
            )
        )

    lines.append("")
    return "\n".join(lines)


def _tick(flag: bool) -> str:
    return "yes" if flag else ""


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    schema_path = Path(argv[0]) if argv else FROZEN_SCHEMA
    doc_path = Path(argv[1]) if len(argv) > 1 else DOC_PATH
    with open(schema_path) as f:
        schema = json.load(f)
    doc_path.parent.mkdir(parents=True, exist_ok=True)
    doc_path.write_text(render(schema))
    print(f"wrote {doc_path} from {schema_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
